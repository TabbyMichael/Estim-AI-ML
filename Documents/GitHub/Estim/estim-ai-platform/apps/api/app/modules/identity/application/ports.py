"""Interface definitions (ports) for the identity module."""

from typing import Protocol

from app.modules.identity.domain.entities import Permission, Role, User


class UserRepository(Protocol):
    def get_by_id(self, user_id: str) -> User: ...
    def get_by_email(self, email: str) -> User: ...
    def exists_by_email(self, email: str) -> bool: ...
    def save(self, user: User) -> User: ...
    def list_users(
        self,
        skip: int = 0,
        limit: int = 50,
        query: str | None = None,
        is_active: bool | None = None,
    ) -> tuple[list[User], int]: ...


class RoleRepository(Protocol):
    def get_by_name(self, name: str) -> Role: ...
    def save(self, role: Role) -> Role: ...
    def list_roles(self) -> list[Role]: ...


class PermissionRepository(Protocol):
    def save(self, permission: Permission) -> Permission: ...
    def list_permissions(self) -> list[Permission]: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, plain: str, hashed: str) -> bool: ...


class TokenIssuer(Protocol):
    def create_access_token(self, subject: str, roles: list[str]) -> str: ...
    def create_refresh_token(self, subject: str) -> str: ...
